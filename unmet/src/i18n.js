/** Country name in the reader's language, falling back to our English table. */
export function countryName(country, lang) {
  if (!country) return '';
  if (lang !== 'en' && country.a2) {
    try {
      const name = new Intl.DisplayNames([lang], { type: 'region' }).of(country.a2);
      if (name && name !== country.a2) return name;
    } catch { /* older browsers: fall through */ }
  }
  return country.name;
}

